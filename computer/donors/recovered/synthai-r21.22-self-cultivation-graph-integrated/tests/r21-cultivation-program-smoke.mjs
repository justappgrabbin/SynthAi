import assert from 'node:assert/strict';
import SynthiaUnit from '../core/SynthiaUnit.mjs';
import {INTERROGATIVE_PROJECTION} from '../organism/CultivationProgram.mjs';
assert.deepEqual(INTERROGATIVE_PROJECTION,{Who:'Space',What:'Evolution',Where:'Being',When:'Movement',Why:'Design'});
const unit=new SynthiaUnit({autoStart:false,residence:{approved:true}});
const c=unit.createCultivationCycle({goal:'make money this week with current constraints',context:'limited transport and cash',purpose:'become materially more capable'});
assert.equal(c.projection.Who.dimension,'Space');
assert.equal(c.projection.What.dimension,'Evolution');
assert.equal(c.projection.Where.dimension,'Being');
assert.equal(c.projection.When.dimension,'Movement');
assert.equal(c.projection.Why.dimension,'Design');
assert.equal(c.how.role,'integration');
assert.ok(c.route.includes('economy'));
assert.ok(c.route.includes('research'));
assert.ok(c.route.includes('builder'));
const before=unit.successSnapshot().cultivation.verifiedProgress;
let x=unit.observeCultivationCycle(c.id,{worked:true,actualOutcome:'identified one viable paid move',evidence:{source:'test',fact:true}});
assert.equal(x.stage,'orientation');
x=unit.observeCultivationCycle(c.id,{worked:false,actualOutcome:'transport blocked it',evidence:{source:'test',fact:true},friction:'transport blocked it'});
assert.ok(unit.successSnapshot().complement.open.length>=1);
assert.equal(unit.successSnapshot().cultivation.verifiedProgress,before+1);
console.log('R21 PASS: five-dimensional cultivation program assembled around real-world outcome feedback');
unit.stopLife();
