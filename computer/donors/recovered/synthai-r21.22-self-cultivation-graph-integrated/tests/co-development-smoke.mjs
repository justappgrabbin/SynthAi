import assert from 'node:assert/strict';
import {SynthiaUnit} from '../core/SynthiaUnit.mjs';
const unit=new SynthiaUnit({autoStart:false,memoryKey:`codev-test-${Date.now()}`});
const e=unit.coDevelop('Joseph stop popping my pimples');
assert.equal(e.type,'co-development-episode');
assert.equal(e.claims.Who.dimension,'Space');
assert.equal(e.claims.What.dimension,'Evolution');
assert.equal(e.claims.Where.dimension,'Being');
assert.equal(e.claims.When.dimension,'Movement');
assert.equal(e.claims.Why.dimension,'Design');
assert.ok(e.unresolved.includes('Why'),'Why should remain unresolved when no purpose is supplied');
assert.match(e.question,/Why did you bring up/i);
assert.equal(e.organism.identity,'Synthia');
assert.equal(e.organism.strongestProcesses.length,8);
const second=unit.coDevelop('I brought it up because I want him to stop touching them');
assert.ok(second.claims.Why.status==='known');
const persisted=unit.coDevelopment.snapshot();
assert.ok(persisted.history.length>=2);
console.log('co-development smoke: PASS');
